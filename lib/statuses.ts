/** Статусы, по которым приложение считает позицию закрытой (просрочки, напоминания): их не переименовывают и не удаляют. */
export const PROTECTED_STATUSES = ["Завершено", "Не актуально"];
/** «На проверке»: в него задача попадает только действием «Сдать на проверку» (колонка трекера «На проверке»). */
export const REVIEW_STATUS = "На проверке";
/** «На стопе»: ставится только действием «Поставить на стоп» (что ждём), снимается — «Снять со стопа». */
export const STOP_STATUS = "На стопе";
/** Системные статусы: не переименовываются, не удаляются, колонка трекера у них закреплена. */
export const SYSTEM_STATUSES = [...PROTECTED_STATUSES, REVIEW_STATUS, STOP_STATUS];
/** Почему статус нельзя менять — подсказка в настройках. */
export function systemStatusHint(name: string): string | null {
  if (PROTECTED_STATUSES.includes(name)) return "Системный статус: по нему считаются просрочки и напоминания, поэтому его не переименовывают и не удаляют.";
  if (name === REVIEW_STATUS) return "Системный статус трекера: в него задачу переводит «Сдать на проверку», поэтому его не переименовывают и не удаляют.";
  if (name === STOP_STATUS) return "Системный статус трекера: его ставит «Поставить на стоп» (с причиной), поэтому его не переименовывают и не удаляют.";
  return null;
}
